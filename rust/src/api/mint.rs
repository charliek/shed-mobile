//! The TokenMinter inversion (plan §3.2) — production shape.
//!
//! The control-token FSM lives in Rust (`shed_core::ControlTokenProvider`), but
//! a mint needs a Dart SSH round-trip. Inversion: [`BridgeMinter`] (installed as
//! the provider's `TokenMinter`) allocates a `request_id`, parks a `oneshot`
//! keyed by it, emits a [`BridgeMintRequest`] on an APP-SCOPED `StreamSink`
//! (D3, routed by `request_id`); Dart mints over dartssh2 and calls
//! [`submit_mint_result`]; Rust completes the `oneshot` and parses the bundle
//! IN RUST via `parse_credential_bundle` (with the expected pin). The whole path
//! runs on `bridge_rt` (FRB's executor has no tokio time driver — B1 finding 2),
//! so `tokio::time::timeout` is valid.
//!
//! Lifecycle invariants (plan §3.2): immutable transport identity in the
//! request; RAII pending-guard so an FRB-dropped future still cleans up; benign
//! rejection of unknown/late/duplicate submits; listener-before-client (a mint
//! with no sink fails fast); a capped pending map; one app-scoped sink with an
//! explicit shutdown seam (B1 finding 3) so Dart's unsubscribe never deadlocks.
//!
//! # mtls enrollment (plan 002 §7 P2/P3)
//!
//! [`BridgeMinter`] implements the generalized minter contract, so the SERVER
//! decides at every mint whether this client gets a bearer token or a client
//! CERTIFICATE. The keypair behind that certificate is generated by
//! `shed_core::ControlTokenProvider` (from `shed_core::csr`), lives in Rust
//! memory for as long as the credential it belongs to, and is never persisted.
//! All this module relays is the provider's base64 CSR — public material — which
//! rides [`BridgeMintRequest::extra_args`] out to Dart and comes back as the raw
//! bundle stdout. No private key exists on any type this module marshals.
//!
//! Secret handling (AC#5): the raw credential-bearing stdout crosses FFI ONLY in
//! the [`submit_mint_result`] payload (Dart→Rust). It is parsed then dropped; it
//! is never logged, never placed in an error/`Display`/`Debug`, never retained
//! past the `oneshot`, and never emitted back to Dart. What crosses back
//! ([`BridgeControlBundle`]) carries the token LENGTH, not bytes. Unit tests
//! destructure the REAL production DTOs field by field (plan 002 §7 P3(b)) and
//! scan the generated FRB surface for key-carrying types.

