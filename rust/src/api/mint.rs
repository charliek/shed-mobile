/// Hard upper bound on a mint round-trip (SSH dial + remote exec + submit). The
/// provider's own cooldown/refresh-window knobs govern *when* a mint happens;
/// this bounds a single in-flight one so a wedged SSH never parks a request
/// forever.
const MINT_TIMEOUT: Duration = Duration::from_secs(45);

/// Cap on concurrently-parked mints. In practice one client mints at a time; a
/// runaway (e.g. a stuck Dart listener) fails fast rather than growing the map.
const MAX_PENDING_MINTS: usize = 64;

/// Hard cap on one `_bootstrap` bundle, enforced before the JSON parser sees it.
///
/// A real bundle is a single JSON line: a token or a PEM certificate, a pin, a
/// port and an expiry — under 1 KiB in token mode, roughly 2 KiB with a
/// certificate. 64 KiB is far past anything a shed-server emits while staying
/// small enough that a hostile endpoint cannot make the app accumulate and parse
/// megabytes.
///
/// It matters most on the ADD-SERVER path, which is the one place this client
/// talks to something the user has not trusted yet: the host key is TOFU, the
/// TLS pin is the thing being learned, and the SSH timeout is generous enough
/// (15–20 s) for a malicious endpoint to stream for a while. Bounding here bounds
/// what is retained and parsed; bounding what is READ off the socket is Dart's
/// half of the job, since the FRB submit hands over one already-built `String`.
const MAX_BUNDLE_BYTES: usize = 64 * 1024;

/// Why Rust is asking Dart to run a `_bootstrap` round-trip. The two purposes
/// differ ONLY in the trust anchor Dart must use for the SSH host key, which is
/// Dart's half of the flow and cannot be decided in Rust:
///   * [`BridgeMintPurpose::ControlMint`] — a saved server: the host key is
///     PINNED to the stored `ServerRecord.hostKeyPin`;
///   * [`BridgeMintPurpose::AddServerPreview`] — first contact ([`preview`]):
///     TOFU, and the fingerprint Dart learns is what the user confirms.
///
/// [`preview`]: super::preview
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BridgeMintPurpose {
    ControlMint,
    AddServerPreview,
}

/// The need-credential request Rust emits to Dart. Carries the IMMUTABLE
/// transport identity (plan §3.2) — not a mutable server-name to be looked up at
/// submit time.
///
/// # `extra_args` — the mtls enrollment channel (plan 002 §7 P2, plan 001 D4)
///
/// The `_bootstrap` request grammar is `<scope> [<kind>] [csr=<base64 std DER>]`.
/// Dart already composes the first two tokens (`control shed-mobile`); this field
/// carries whatever else the mint needs — today exactly one `csr=…` argument, or
/// nothing for a CSR-less mint. **Dart appends these VERBATIM**: they are
/// already in wire form.
///
/// That "verbatim" is load-bearing, not stylistic. shed-server reads the request
/// line with `sess.RawCommand()` and splits it on whitespace — there is no shell
/// on that path, so a POSIX-quoted argument arrives WITH its quotes and the
/// `csr=` prefix match fails. Standard base64 uses `+` and `=`, which mobile's
/// `shellQuote` does not consider bare-safe, so routing these through
/// `wireCmd`/`shellQuote` would silently produce `'csr=…'` and an mtls server
/// would answer "this server requires auth.mode: mtls; upgrade shed". The M2 Dart
/// change must append them to the composed command string, not through the
/// quoter, and its injected-`SshRun` test asserts the exact argv.
///
/// Key containment (§7 P3): a CSR is a PUBLIC artifact — the private half stays
/// in the `ControlTokenProvider` that generated it (control mint) or in the
/// preview future (add-server), and no field on this type can carry it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BridgeMintRequest {
    pub request_id: String,
    pub purpose: BridgeMintPurpose,
    pub host: String,
    pub ssh_port: u16,
    pub base_url: String,
    pub expected_tls_pin: Option<String>,
    /// Extra `_bootstrap` arguments, appended VERBATIM after `control <kind>`.
    pub extra_args: Vec<String>,
}

/// The `_bootstrap` extra arguments for a credential request: the CSR argument
/// when the provider handed us one, nothing otherwise.
///
/// One place composes the wire form, so the mint path and the add-server preview
/// can never drift apart, and `csr=` is spelled exactly once in this crate.
pub(crate) fn csr_extra_args(csr_base64: Option<&str>) -> Vec<String> {
    match csr_base64 {
        Some(csr) => vec![format!("csr={csr}")],
        None => Vec::new(),
    }
}

/// Dart's answer to a mint request — a real FRB 2.13 sealed enum (the B1
/// tagged-struct workaround is retired). `Success` carries the raw
/// `shed-ext-rc`-style bundle stdout (the token-bearing payload); `Failure`
/// carries a non-secret code.
pub enum BridgeMintOutcome {
    Success { raw_stdout: String },
    Failure { code: String },
}

/// The parsed control bundle returned to Dart from [`demo_mint`] — TOKEN OMITTED
/// (only its length crosses back; AC#5).
pub struct BridgeControlBundle {
    pub token_present: bool,
    pub token_len: u32,
    pub expires_at_unix: u64,
    pub tls_cert_fingerprint: String,
    pub https_port: u16,
}

/// The typed failure of the shared mint core, so the caller can preserve a
/// `TokenBundleError` (Codex review #3) instead of stringifying it.
pub(crate) enum RunMintError {
    Message(String),
    Token(TokenBundleError),
}

impl RunMintError {
    /// Collapse into the only error type a `TokenMinter` may return, tunnelling a
    /// typed bundle error through the marked transport message
    /// (`error::TOKEN_ERR_MARKER`) so `From<ShedError>` can recover it. Both
    /// shapes are non-secret.
    pub(crate) fn into_shed_error(self) -> ShedError {
        ShedError::Transport(match self {
            RunMintError::Message(m) => m,
            RunMintError::Token(t) => encode_token_err(&t),
        })
    }
}

/// The raw `_bootstrap` bundle stdout, straight off the wire.
///
/// A newtype rather than a bare `String` for one reason: in token mode this text
/// IS the bearer token (plus its envelope), so it must never reach a log line, an
/// error payload, or a `{:?}` of an enclosing type. `Debug` is redacted, there is
/// no `Display`, and the only accessor hands out a borrowed `&str` for a parser
/// to consume — the value itself is dropped at the end of the mint that produced
/// it and never travels back across FFI.
pub(crate) struct RawBundle(String);

impl RawBundle {
    pub(crate) fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Debug for RawBundle {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("RawBundle")
            .field("stdout", &"<redacted>")
            .field("len", &self.0.len())
            .finish()
    }
}

/// How a parked mint resolves: Dart submitted, the bridge-runtime timer fired,
/// or the sink was shut down out from under it (Codex review #2).
enum MintResolution {
    Submitted(BridgeMintOutcome),
    TimedOut,
    SinkShutdown,
}

/// The app-scoped mint sink (plan D3: ONE shared sink routed by `request_id`),
/// with its generation and shutdown signal in the same atomically-swapped slot —
/// see [`SinkRegistry`] for the two races that shape demanded.
pub(crate) static MINT_SINK: SinkRegistry<BridgeMintRequest> = SinkRegistry::new();

// request_id -> oneshot sender awaiting Dart's submit (or the timer).
static PENDING: OnceLock<Mutex<HashMap<String, oneshot::Sender<MintResolution>>>> = OnceLock::new();

fn pending() -> &'static Mutex<HashMap<String, oneshot::Sender<MintResolution>>> {
    PENDING.get_or_init(|| Mutex::new(HashMap::new()))
}

/// Remove a pending entry, decrementing the leak counter IFF it was present.
/// The single mutation point, so the counter always matches the map exactly and
/// exactly one of {submit, timer, drop-guard} decrements per request.
fn take_pending(id: &str) -> Option<oneshot::Sender<MintResolution>> {
    let removed = pending().lock().unwrap().remove(id);
    if removed.is_some() {
        PENDING_MINTS.fetch_sub(1, Ordering::SeqCst);
    }
    removed
}

/// Register the app-scoped mint StreamSink and stay alive until
/// [`shutdown_mint_sink`] fires (keeping the FRB stream open for the app's
/// lifetime). Dart listens BEFORE any `BridgeClient` is constructed
/// (listener-before-client); a `mint` emitted with no sink fails fast.
///
/// Generation-guarded (Codex review #1): each registration takes a fresh
/// generation and, if a prior sink is live, evicts it FIRST (drains its pending
/// under the same lock, then fires its shutdown). When this task's await
/// returns, it clears the slot ONLY if it still owns the generation — so a later
/// sink B installed while A's task was parked is never clobbered by A.
pub async fn set_mint_sink(sink: StreamSink<BridgeMintRequest>) {
    let (generation, srx) = install_mint_sink(std::sync::Arc::new(sink));
    let _ = srx.await; // parks until shutdown_mint_sink() fires, then returns
    MINT_SINK.release(generation);
}

/// The ONE install point for the mint sink, so the eviction semantics —
/// "resolve the outgoing sink's parked mints under the same lock that removes
/// it" — are shared by production and by the tests that register a fake.
pub(crate) fn install_mint_sink(
    emitter: std::sync::Arc<dyn Emitter<BridgeMintRequest>>,
) -> (u64, oneshot::Receiver<()>) {
    MINT_SINK.install(emitter, drain_pending_locked)
}

/// End the mint sink fn cleanly (Dart calls this in `onDispose` before
/// unsubscribing). Idempotent. Resolves EVERY parked mint immediately with a
/// non-secret `SinkShutdown` (Codex review #2 — no more 45 s strand), then fires
/// the sink's shutdown signal. Synchronous so Riverpod `onDispose` can call it
/// without an unawaitable future (Codex review #9).
///
/// Removal and drain happen under ONE lock, which closes the window a split
/// implementation left open: a mint that parked after the drain but before the
/// sink was cleared used to stay parked to its 45 s timer even though its
/// listener was already gone. Now the emit that follows such a park sees no
/// sink and fails immediately.
#[frb(sync)]
pub fn shutdown_mint_sink() {
    MINT_SINK.shutdown(drain_pending_locked);
}

/// Resolve and remove EVERY parked mint with `SinkShutdown`, keeping the leak
/// counter exact (Codex review #2 — never strand a parked mint for the 45 s
/// timeout when the sink goes away).
///
/// Called only from inside [`SinkRegistry`]'s slot lock (install-eviction and
/// shutdown), so "the sink is gone" and "its parked work is resolved" are one
/// indivisible step. Lock order is registry → pending, and nothing takes them
/// the other way round: [`run_mint_raw`] parks (pending) and releases before it
/// emits (registry).
pub(crate) fn drain_pending_locked() {
    let entries: Vec<(String, oneshot::Sender<MintResolution>)> =
        pending().lock().unwrap().drain().collect();
    for (_id, tx) in entries {
        PENDING_MINTS.fetch_sub(1, Ordering::SeqCst);
        let _ = tx.send(MintResolution::SinkShutdown);
    }
}

/// RAII guard: on drop (normal return, error, OR FRB-cancel of the outer future)
/// remove the pending entry if still present — the drop-safe cleanup path.
struct PendingGuard {
    id: String,
}
impl Drop for PendingGuard {
    fn drop(&mut self) {
        let _ = take_pending(&self.id);
    }
}

/// The shared inversion core: emit a need-credential request → await Dart's
/// submit (bounded) → return the RAW bundle stdout for the caller to parse.
///
/// Three callers, three different parses, one round-trip implementation:
/// [`BridgeMinter::mint_credential`] (the mint path — `parse_credential_bundle`,
/// pin and port already known), [`super::preview::preview_add_server`] (first
/// contact — the stricter `parse_control_bundle`), and [`demo_mint`].
///
/// The returned [`RawBundle`] is credential-bearing; see its doc for why it is a
/// redacted newtype and not a `String`.
pub(crate) async fn run_mint_raw(
    purpose: BridgeMintPurpose,
    host: String,
    ssh_port: u16,
    base_url: String,
    expected_tls_pin: Option<String>,
    extra_args: Vec<String>,
    timeout: Duration,
) -> Result<RawBundle, RunMintError> {
    let request_id = next_id("mint");
    let (tx, rx) = oneshot::channel::<MintResolution>();

    // Cap + park BEFORE emitting, so a submit that races in can never find an
    // empty map. The guard cleans it up on any exit path.
    {
        let mut map = pending().lock().unwrap();
        if map.len() >= MAX_PENDING_MINTS {
            return Err(RunMintError::Message(
                "mint rejected: too many pending mint requests".to_string(),
            ));
        }
        map.insert(request_id.clone(), tx);
    }
    PENDING_MINTS.fetch_add(1, Ordering::SeqCst);
    let _guard = PendingGuard {
        id: request_id.clone(),
    };

    // Emit to the app-scoped sink (fail fast if none registered / closed).
    emit_request(BridgeMintRequest {
        request_id: request_id.clone(),
        purpose,
        host,
        ssh_port,
        base_url,
        expected_tls_pin,
        extra_args,
    })?;

    // Timeout driver on bridge_rt (FRB's executor has no time driver): after the
    // deadline, resolve the same oneshot with TimedOut if still pending.
    {
        let id = request_id.clone();
        bridge_rt().spawn(async move {
            tokio::time::sleep(timeout).await;
            if let Some(tx) = take_pending(&id) {
                let _ = tx.send(MintResolution::TimedOut);
            }
        });
    }

    // Await resolution — a plain channel await (safe on any executor).
    let outcome = match rx
        .await
        .map_err(|_| RunMintError::Message("mint channel dropped".to_string()))?
    {
        MintResolution::TimedOut => {
            return Err(RunMintError::Message(
                "mint timed out awaiting submit_mint_result".to_string(),
            ))
        }
        MintResolution::SinkShutdown => {
            return Err(RunMintError::Message("mint sink shut down".to_string()))
        }
        MintResolution::Submitted(o) => o,
    };

    match outcome {
        BridgeMintOutcome::Success { raw_stdout } => {
            // Fail closed on an oversized payload BEFORE it reaches a JSON parser
            // (see MAX_BUNDLE_BYTES). Only the length is reported — never a byte
            // of the payload, which in token mode is the credential itself.
            if raw_stdout.len() > MAX_BUNDLE_BYTES {
                return Err(RunMintError::Message(format!(
                    "bootstrap response too large: {} bytes (cap {MAX_BUNDLE_BYTES})",
                    raw_stdout.len()
                )));
            }
            Ok(RawBundle(raw_stdout))
        }
        BridgeMintOutcome::Failure { code } => {
            Err(RunMintError::Message(format!("mint failed: {code}")))
        }
    }
}

/// Hand one request to the app-scoped sink, failing fast when Dart is not
/// listening (listener-before-client) or the stream is closed. Never parks on a
/// sink that has gone away — that is the whole point of routing every emit
/// through the registry's single lock.
fn emit_request(req: BridgeMintRequest) -> Result<(), RunMintError> {
    MINT_SINK.emit(req).map_err(|e| {
        RunMintError::Message(
            match e {
                EmitError::NoSink => {
                    "no mint sink registered (listener-before-client violated, or the sink shut down)"
                }
                EmitError::Closed => "mint sink closed",
            }
            .to_string(),
        )
    })
}

/// [`run_mint_raw`] plus the strict add-server parse, for [`demo_mint`].
async fn run_mint(
    host: String,
    ssh_port: u16,
    base_url: String,
    expected_tls_pin: Option<String>,
    timeout: Duration,
) -> Result<ControlBundle, RunMintError> {
    let raw = run_mint_raw(
        BridgeMintPurpose::ControlMint,
        host,
        ssh_port,
        base_url,
        expected_tls_pin.clone(),
        Vec::new(),
        timeout,
    )
    .await?;
    // Parse IN RUST with the expected pin (a mismatch is a hard error, not a
    // silently-accepted bundle). Preserve the TYPED error (Codex #3). The raw
    // stdout is dropped at the end of this fn.
    shed_core::token::parse_control_bundle(raw.as_str(), expected_tls_pin.as_deref())
        .map_err(RunMintError::Token)
}

/// The production minter: installed as a `ControlTokenProvider`'s `TokenMinter`
/// so a real client request that needs a fresh control token drives the Dart
/// SSH round-trip. Carries the immutable transport identity (plan §3.2).
pub(crate) struct BridgeMinter {
    pub host: String,
    pub ssh_port: u16,
    pub base_url: String,
    pub expected_tls_pin: Option<String>,
}

#[async_trait::async_trait]
impl TokenMinter for BridgeMinter {
    /// Mobile ALWAYS supports mtls — unconditionally, with no capability
    /// negotiation anywhere in the stack.
    ///
    /// The mint is INVERTED here (plan §3.2): Dart owns no protocol knowledge, it
    /// runs the `_bootstrap` SSH command and hands the raw stdout back. A CSR is
    /// therefore just another argument string for Dart to relay
    /// ([`BridgeMintRequest::extra_args`]), so there is no version of this app
    /// that can carry the CSR out but not the certificate back — the two travel
    /// on the same wire the token already used. That is the difference from the
    /// desktop, where the minter is a SEPARATE PROCESS (shed-host-agent) that may
    /// be older than the app and must advertise its capability over the UDS
    /// (§7 P5's tri-state). Nothing analogous exists here: there is no second
    /// process, no version skew, and consequently nothing to negotiate.
    ///
    /// Saying `true` does not ask for a certificate — the SERVER still chooses
    /// the credential shape at every mint (D5). It only means "if you issue one,
    /// this client can complete the enrollment".
    fn supports_mtls(&self) -> bool {
        true
    }

    /// Mint whatever credential the server issues, relaying the provider's CSR.
    ///
    /// The keypair behind `req` was generated by the provider
    /// (`shed_core::csr::ClientKeyPair`, one per mint) and stays there; this
    /// method only sees `csr_base64()`, the public half in wire form. A
    /// certificate that comes back is paired with that key by the provider, which
    /// refuses one it did not request a CSR for.
    async fn mint_credential(
        &self,
        _server: &str,
        req: &CredentialRequest,
    ) -> Result<MintedCredential, ShedError> {
        let raw = run_mint_raw(
            BridgeMintPurpose::ControlMint,
            self.host.clone(),
            self.ssh_port,
            self.base_url.clone(),
            self.expected_tls_pin.clone(),
            csr_extra_args(req.csr_base64()),
            MINT_TIMEOUT,
        )
        .await
        // The trait can only return ShedError, so tunnel a typed TokenBundleError
        // through a MARKED transport message (Codex #3) — the client error path
        // (`From<ShedError>`) recovers it into TokenPinMismatch/PinMissing/
        // AuthExpired. A plain message stays a normal transport error. Both are
        // non-secret (the mint never surfaces credential bytes); the provider's
        // posture stays "no credential on failure" (no downgrade).
        .map_err(RunMintError::into_shed_error)?;

        // The MINT-path parse: the pin and https port are already known (the
        // transport exists), so only the credential and its expiry are required.
        // A present fingerprint that disagrees with the pin is still a hard error.
        parse_credential_bundle(raw.as_str(), self.expected_tls_pin.as_deref())
            .map_err(|t| RunMintError::Token(t).into_shed_error())
    }

    /// The legacy token-only entry point. Production never reaches it — the
    /// provider calls [`Self::mint_credential`] — but the trait requires it, and
    /// leaving it as a CSR-less mint keeps the two paths honest: a server that
    /// answers this one with a certificate is answering a request that carried no
    /// CSR, so the key would be one this process does not hold. Refused rather
    /// than unwrapped into an unusable credential.
    async fn mint(&self, server: &str) -> Result<MintedToken, ShedError> {
        match self
            .mint_credential(server, &CredentialRequest::default())
            .await?
        {
            MintedCredential::Token(t) => Ok(t),
            MintedCredential::Certificate(_) => Err(ShedError::Transport(
                "mint returned a client certificate for a request that carried no CSR".into(),
            )),
        }
    }
}

/// The direct integration proof of the full inversion (retained from B1): emit →
/// await Dart's submit → parse in Rust → return the NON-SECRET fields (token
/// length only). The real app never calls this; `BridgeClient` mints via the
/// provider path. Kept because it exercises the inversion end-to-end from Dart
/// without needing a live shed-server.
pub async fn demo_mint(
    host: String,
    ssh_port: u16,
    base_url: String,
    expected_tls_pin: Option<String>,
    timeout_ms: u64,
) -> Result<BridgeControlBundle, String> {
    let bundle = run_mint(
        host,
        ssh_port,
        base_url,
        expected_tls_pin,
        Duration::from_millis(timeout_ms),
    )
    .await
    .map_err(|e| match e {
        RunMintError::Message(m) => m,
        RunMintError::Token(t) => t.to_string(),
    })?;
    Ok(BridgeControlBundle {
        token_present: !bundle.token.is_empty(),
        token_len: bundle.token.len() as u32,
        expires_at_unix: bundle.expires_at_unix,
        tls_cert_fingerprint: bundle.tls_cert_fingerprint,
        https_port: bundle.https_port,
    })
}

/// Dart submits its mint result here. Benign no-op ("rejected") for an unknown /
/// late / duplicate `request_id` — never a panic. Single-resume via remove.
pub fn submit_mint_result(request_id: String, outcome: BridgeMintOutcome) -> String {
    match take_pending(&request_id) {
        Some(tx) => match tx.send(MintResolution::Submitted(outcome)) {
            Ok(()) => "accepted".to_string(),
            // Receiver already gone (timed out / cancelled) — benign.
            Err(_) => "rejected (already resolved)".to_string(),
        },
        None => "rejected (unknown request_id)".to_string(),
    }
}

